import { createCatalog } from './features/catalog.js';
import { createChats } from './features/chats.js';
import { createDesign } from './features/design.js';
import { createAdapter } from './engine/adapter.js';
import { createNotifications } from './features/notifications.js';
import { createHub } from './ui/hub.js';
import { createExtensions } from './engine/extensions.js';
